export const GLYPH_W = 5;
export const GLYPH_H = 7;

/**
 * Rasterises text into columns: an array where each entry is a 7-bit column,
 * bit 0 the top row. A one-column gap follows every glyph.
 */
export function rasterise(text) {
  const cols = [];
  for (const ch of text.toUpperCase()) {
    const rows = GLYPHS[ch] || GLYPHS[" "];
    for (let x = 0; x < GLYPH_W; x++) {
      let bits = 0;
      for (let y = 0; y < GLYPH_H; y++) if (rows[y][x] === "1") bits |= 1 << y;
      cols.push(bits);
    }
    cols.push(0);
  }
  return cols;
}
